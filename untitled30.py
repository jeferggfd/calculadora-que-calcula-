import streamlit as st
import numpy as np

# Configuración de la página
st.set_page_config(page_title="Calculadora Matemática de Pasita", page_icon="🧮", layout="centered")

st.title("🧮 Mi Calculadora Matemática Interactiva")
st.markdown("Bienvenida a la aplicación de operaciones matemáticas con **Streamlit**.")

# --- BARRA LATERAL (menu de operacione) ---
st.sidebar.title("pagina de matematicas pasita")
modo = st.sidebar.selectbox(
    "Selecciona el tipo de operación:",
    ["Operaciones Básicas", "Ecuación Cuadrática (Ax² + Bx + C)", "Geometría Básica"]
)

st.sidebar.markdown("---")
st.sidebar.text("Desarrollado para Programación 🚀")
st.sidebar.image("images.jpg")

# --- SECCIÓN 1: OPERACIONES BÁSICAS ---
if modo == "Operaciones Básicas":
    st.header("➕ Operaciones Aritméticas Básicas")

    col1, col2 = st.columns(2)
    with col1:
        num1 = st.number_input("Ingresa el primer número:", value=10.0)
    with col2:
        num2 = st.number_input("Ingresa el segundo número:", value=5.0)

    operacion = st.radio("Elige la operación:", ["Suma (+)", "Resta (-)", "Multiplicación (×)", "División (÷)", "Potencia (^)"])

    if st.button("Calcular Operación"):
        if operacion == "Suma (+)":
            resultado = num1 + num2
            st.success(f"El resultado de la suma es: **{resultado}**")
        elif operacion == "Resta (-)":
            resultado = num1 - num2
            st.success(f"El resultado de la resta es: **{resultado}**")
        elif operacion == "Multiplicación (×)":
            resultado = num1 * num2
            st.success(f"El resultado de la multiplicación es: **{resultado}**")
        elif operacion == "División (÷)":
            if num2 != 0:
                resultado = num1 / num2
                st.success(f"El resultado de la división es: **{resultado}**")
            else:
                st.error("¡Error! No se puede dividir entre cero.")
        elif operacion == "Potencia (^)":
            resultado = num1 ** num2
            st.success(f"El resultado de la potencia es: **{resultado}**")


# --- SECCIÓN 2: ECUACIÓN CUADRÁTICA ---
elif modo == "Ecuación Cuadrática (Ax² + Bx + C)":
    st.header("📈 Resolución de Ecuaciones de 2do Grado")
    st.latex(r"ax^2 + bx + c = 0")

    col1, col2, col3 = st.columns(3)
    with col1:
        a = st.number_input("Valor de a:", value=1.0)
    with col2:
        b = st.number_input("Valor de b:", value=-3.0)
    with col3:
        c = st.number_input("Valor de c:", value=2.0)

    if st.button("Resolver Ecuación"):
        if a == 0:
            st.warning("El valor de 'a' no puede ser cero en una ecuación cuadrática.")
        else:
            # Cálculo del discriminante
            discriminante = (b**2) - (4 * a * c)
            st.write(f"Discriminante ($\Delta$): **{discriminante}**")

            if discriminante > 0:
                x1 = (-b + np.sqrt(discriminante)) / (2 * a)
                x2 = (-b - np.sqrt(discriminante)) / (2 * a)
                st.success(f"Tiene dos soluciones reales distintas:")
                st.write(f"- $x_1 = {x1}$")
                st.write(f"- $x_2 = {x2}$")
            elif discriminante == 0:
                x = -b / (2 * a)
                st.success(f"Tiene una solución única (raíz doble): $x = {x}$")
            else:
                parte_real = -b / (2 * a)
                parte_imag = np.sqrt(abs(discriminante)) / (2 * a)
                st.success("Tiene soluciones complejas (imaginarias):")
                st.write(f"- $x_1 = {parte_real} + {parte_imag}i$")
                st.write(f"- $x_2 = {parte_real} - {parte_imag}i$")


# --- SECCIÓN 3: GEOMETRÍA ---
elif modo == "Geometría Básica":
    st.header("📐 Cálculo de Áreas Geométricas")

    figura = st.selectbox("Selecciona una figura:", ["Círculo", "Rectángulo", "Triángulo"])

    if figura == "Círculo":
        radio = st.number_input("Ingresa el radio del círculo:", value=5.0)
        if st.button("Calcular Área"):
            area = np.pi * (radio ** 2)
            perimetro = 2 * np.pi * radio
            st.success(f"Área del círculo: **{area:.2f}**")
            st.info(f"Perímetro (Circunferencia): **{perimetro:.2f}**")

    elif figura == "Rectángulo":
        base = st.number_input("Base del rectángulo:", value=4.0)
        altura = st.number_input("Altura del rectángulo:", value=6.0)
        if st.button("Calcular Área"):
            area = base * altura
            perimetro = 2 * (base + altura)
            st.success(f"Área del rectángulo: **{area:.2f}**")
            st.info(f"Perímetro del rectángulo: **{perimetro:.2f}**")

    elif figura == "Triángulo":
        base = st.number_input("Base del triángulo:", value=3.0)
        altura = st.number_input("Altura del triángulo:", value=4.0)
        if st.button("Calcular Área"):
            area = (base * altura) / 2
            st.success(f"Área del triángulo: **{area:.2f}**")
